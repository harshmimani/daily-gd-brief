#!/usr/bin/env python3
"""Build the small data files the Upcoming, Library, Review and watchlist views read.

Runs after every build and backfill. It only reads the archived briefs, so
nothing here is generated by a model:

  data/library.json      every term and concept the brief has explained
  data/review.json       flashcards: quotable facts, terms and concepts, by date
  data/stories.json      a compact index of recent stories for watchlist matching
  data/news-events.json  future dates named in recent stories (date-checked upstream)

data/calendar.json (scheduled events) is maintained by hand and is not touched.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IST = timezone(timedelta(hours=5, minutes=30))
STORY_DAYS = 30        # watchlist index window
EVENT_DAYS = 45        # how far back to look for dated events
REVIEW_DAYS = 60       # flashcard window

NUMBER = re.compile(r"\d")


def short_cat(title: str) -> str:
    return re.split(r"[,&:]", title or "")[0].strip()


def card_id(*parts: str) -> str:
    return hashlib.sha1("|".join(parts).encode("utf-8")).hexdigest()[:12]


def load_briefs(archive: Path) -> list[dict]:
    briefs = []
    for f in sorted(archive.glob("20??-??-??.json")):
        try:
            briefs.append(json.loads(f.read_text(encoding="utf-8")))
        except Exception:  # noqa: BLE001
            continue
    return [b for b in briefs if b.get("date")]


def build(root: Path = ROOT, today: str | None = None) -> dict:
    data = root / "data"
    archive = data / "archive"
    today = today or datetime.now(IST).strftime("%Y-%m-%d")
    t = datetime.strptime(today, "%Y-%m-%d").date()
    briefs = load_briefs(archive)

    def within(b: dict, days: int) -> bool:
        return (t - datetime.strptime(b["date"], "%Y-%m-%d").date()).days <= days

    # ---- library: terms and concepts --------------------------------------
    terms: dict[str, dict] = {}
    concepts: dict[str, dict] = {}
    for b in briefs:
        c = b.get("concept") or {}
        if c.get("name") and c.get("explanation"):
            concepts[c["name"].strip().lower()] = {
                "name": c["name"].strip(), "date": b["date"],
                "explanation": c.get("explanation", ""), "indian_example": c.get("indian_example", ""),
                "use_in_gd": c.get("use_in_gd", ""),
            }
        for cat in b.get("categories", []):
            for s in cat.get("stories", []):
                kt = s.get("key_term")
                if isinstance(kt, dict) and kt.get("term") and kt.get("meaning"):
                    key = re.sub(r"\s+", " ", kt["term"].strip().lower())
                    terms[key] = {
                        "term": kt["term"].strip(), "meaning": kt["meaning"].strip(), "date": b["date"],
                        "category": cat.get("key"), "category_title": short_cat(cat.get("title", "")),
                        "story": s.get("title", ""), "url": s.get("url", ""), "source": s.get("source", ""),
                    }
    library = {
        "updated": today,
        "terms": sorted(terms.values(), key=lambda x: x["term"].lower()),
        "concepts": sorted(concepts.values(), key=lambda x: x["date"], reverse=True),
    }

    # ---- review deck ------------------------------------------------------
    cards = []
    for b in briefs:
        if not within(b, REVIEW_DAYS):
            continue
        c = b.get("concept") or {}
        if c.get("name") and c.get("explanation"):
            cards.append({"id": card_id("c", c["name"]), "kind": "concept", "date": b["date"],
                          "front": c["name"], "back": c["explanation"], "category": "concept"})
        for cat in b.get("categories", []):
            for s in cat.get("stories", []):
                if not s.get("ai"):
                    continue
                fact = (s.get("key_fact") or "").strip()
                if fact and not s.get("fact_is_context") and NUMBER.search(fact):
                    cards.append({"id": card_id("f", s.get("url", ""), fact), "kind": "fact", "date": b["date"],
                                  "front": s.get("title", ""), "back": fact,
                                  "category": cat.get("key"), "category_title": short_cat(cat.get("title", "")),
                                  "url": s.get("url", ""), "source": s.get("source", "")})
                kt = s.get("key_term")
                if isinstance(kt, dict) and kt.get("term") and kt.get("meaning"):
                    cards.append({"id": card_id("t", kt["term"].lower()), "kind": "term", "date": b["date"],
                                  "front": kt["term"], "back": kt["meaning"],
                                  "category": cat.get("key"), "category_title": short_cat(cat.get("title", ""))})
    seen = set()
    deck = []
    for c in sorted(cards, key=lambda x: x["date"], reverse=True):
        if c["id"] in seen:
            continue
        seen.add(c["id"])
        deck.append(c)
    review = {"updated": today, "cards": deck}

    # ---- story index for the watchlist ------------------------------------
    stories = []
    for b in briefs:
        if not within(b, STORY_DAYS):
            continue
        for cat in b.get("categories", []):
            for s in cat.get("stories", []):
                stories.append({
                    "date": b["date"], "category": cat.get("key"), "title": s.get("title", ""),
                    "url": s.get("url", ""), "source": s.get("source", ""),
                    "summary": (s.get("summary") or "")[:160],
                })
    stories.sort(key=lambda x: x["date"], reverse=True)

    # ---- dated events from the news ---------------------------------------
    events: dict[tuple[str, str], dict] = {}
    for b in briefs:
        if not within(b, EVENT_DAYS):
            continue
        for cat in b.get("categories", []):
            for s in cat.get("stories", []):
                for e in s.get("upcoming") or []:
                    d = str(e.get("date", ""))[:10]
                    what = str(e.get("event", "")).strip()
                    if not d or not what or d < today:
                        continue
                    key = (d, re.sub(r"[^a-z0-9]+", " ", what.lower()).strip()[:60])
                    events[key] = {"date": d, "event": what, "category": cat.get("key"),
                                   "story": s.get("title", ""), "url": s.get("url", ""),
                                   "source": s.get("source", ""), "reported": b["date"]}
    news_events = {"updated": today, "events": sorted(events.values(), key=lambda x: x["date"])}

    out = {
        "library.json": library, "review.json": review,
        "stories.json": {"updated": today, "stories": stories},
        "news-events.json": news_events,
    }
    for name, obj in out.items():
        (data / name).write_text(json.dumps(obj, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    return {
        "terms": len(library["terms"]), "concepts": len(library["concepts"]),
        "cards": len(deck), "stories": len(stories), "news_events": len(news_events["events"]),
    }


if __name__ == "__main__":
    stats = build()
    print("Derived data:", ", ".join(f"{k} {v}" for k, v in stats.items()))
    sys.exit(0)
